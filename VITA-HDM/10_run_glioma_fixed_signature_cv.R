add_pairwise_contrast <- function(df, model_a, model_b, label) {
  if (!(model_a %in% colnames(df)) || !(model_b %in% colnames(df))) {
    return(NULL)
  }
  diff_vec <- df[[model_a]] - df[[model_b]]
  diff_vec <- diff_vec[is.finite(diff_vec)]
  if (length(diff_vec) == 0) {
    return(NULL)
  }
  data.frame(
    Contrast = label,
    Model_A = model_a,
    Model_B = model_b,
    N = length(diff_vec),
    Mean_Difference = mean(diff_vec),
    SD_Difference = ifelse(length(diff_vec) > 1, sd(diff_vec), NA_real_),
    Positive_N = sum(diff_vec > 0),
    stringsAsFactors = FALSE
  )
}
