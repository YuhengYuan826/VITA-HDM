read_gene_csv <- function(path, target_expr, required = FALSE, label = "signature") {
  if (!file.exists(path)) {
    if (required) stop("Cannot find ", label, " CSV: ", path)
    return(character(0))
  }
  df <- read.csv(path, stringsAsFactors = FALSE)
  if (nrow(df) == 0) {
    if (required) stop(label, " CSV is empty: ", path)
    return(character(0))
  }
  if (!("Raw_Gene" %in% colnames(df))) {
    if (!("Gene" %in% colnames(df))) {
      stop(label, " CSV must contain either Raw_Gene or Gene column: ", path)
    }
    df$Raw_Gene <- sub("^M_", "", df$Gene)
  }
  genes <- unique(as.character(df$Raw_Gene))
  genes <- genes[genes != ""]
  intersect(genes, rownames(target_expr))
}
target_anchored_path <- if (file.exists(TARGET_ANCHORED_CSV)) {
  TARGET_ANCHORED_CSV
} else {
  MANUSCRIPT_CSV
}
target_anchored_genes <- read_gene_csv(
  path = target_anchored_path,
