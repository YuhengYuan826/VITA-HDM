#   5. Clinical + VITA-HDM target-anchored reported set
# Important:
#   This is a descriptive fixed-signature predictive assessment.
#   It is not a fully nested discovery-validation estimate because signatures are
#   read from the discovery object generated by
#   09_run_glioma_discovery.R.
# Outputs:
#   results/case_study/fixed_signature_cv/
