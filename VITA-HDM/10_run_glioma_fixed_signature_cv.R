all_needed_genes <- intersect(all_needed_genes, rownames(target$expr))
# ------------------------------------------------------------------------------
# Repeated CV
# ------------------------------------------------------------------------------
fold_rows <- list()
row_id <- 1
clin_vars <- c("D", COVARIATES)
set.seed(CV_SEED)
for (r in seq_len(REPEATS)) {
  cat("Repeat", r, "/", REPEATS, "\n")
  fold_list <- make_stratified_folds(
    target$clinical$OS_status,
    k = FOLDS,
    seed = CV_SEED + r
  )
  for (k in seq_len(FOLDS)) {
    test_idx <- fold_list[[k]]
    train_idx <- setdiff(seq_len(nrow(target$clinical)), test_idx)
    dat_target <- make_cox_fold_data_target(
      target_cohort = target,
      idx_train = train_idx,
      idx_test = test_idx,
      raw_genes = all_needed_genes,
      covariates = COVARIATES,
      binary_covariates = BINARY_COVARIATES
    )
    train_df <- dat_target$train
    test_df <- dat_target$test
    c_clin <- fit_cox_cindex(
      train_df = train_df,
      test_df = test_df,
      vars = clin_vars
    )
    fold_rows[[row_id]] <- data.frame(
      Repeat = r,
      Fold = k,
      Model = "Clinical-Only",
      N_Genes = 0,
      Training_Domain = "Target",
      C_Index = c_clin,
      Delta_vs_Clinical = 0,
      stringsAsFactors = FALSE
    )
    row_id <- row_id + 1
    # --------------------------------------------------------------------------
    # Source-trained Cox comparator using the target-anchored reported set.
    # The signature is fixed from discovery, but coefficients are trained in source.
    # --------------------------------------------------------------------------
    target_test_clin <- target$clinical[test_idx, , drop = FALSE]
    source_dat <- make_cox_source_train_target_test(
      source_cohort = source_cohort,
      target_test_clin = target_test_clin,
      target_expr = target$expr,
      raw_genes = target_anchored_genes,
      covariates = COVARIATES,
      binary_covariates = BINARY_COVARIATES
    )
    source_vars <- c(clin_vars, paste0("M_", target_anchored_genes))
    
    c_source <- fit_cox_cindex(
      train_df = source_dat$train,
      test_df = source_dat$test,
      vars = source_vars
    )
    fold_rows[[row_id]] <- data.frame(
      Repeat = r,
      Fold = k,
      Model = paste0("Source-Only_", source_cohort$cohort, "_TargetAnchored_Set"),
      N_Genes = length(target_anchored_genes),
      Training_Domain = "Source",
      C_Index = c_source,
      Delta_vs_Clinical = c_source - c_clin,
      stringsAsFactors = FALSE
    )
    row_id <- row_id + 1
    # --------------------------------------------------------------------------
    # Target-trained fixed signatures.
    # --------------------------------------------------------------------------
    for (nm in names(signature_list)) {
      raw_genes <- signature_list[[nm]]
      gene_vars <- paste0("M_", raw_genes)
      vars <- c(clin_vars, gene_vars)
      c_sig <- fit_cox_cindex(
        train_df = train_df,
        test_df = test_df,
        vars = vars
      )
      fold_rows[[row_id]] <- data.frame(
        Repeat = r,
        Fold = k,
        Model = paste0("Clinical + ", nm),
        N_Genes = length(raw_genes),
        Training_Domain = "Target",
        C_Index = c_sig,
        Delta_vs_Clinical = c_sig - c_clin,
        stringsAsFactors = FALSE
      )
      row_id <- row_id + 1
    }
  }
}
